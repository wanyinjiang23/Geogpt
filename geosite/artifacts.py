"""Offline SVG map plus RFC7946 GeoJSON and auditable reports."""

import csv
import html
import json
from pathlib import Path

from pyproj import Transformer
from shapely import transform
from shapely.geometry import Point, mapping

from .gis import ANALYSIS_CRS


def write_json(path: Path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False), encoding="utf-8")


def export(directory: Path, rows, feasible, excluded, layers, request, metadata):
    top = rows[: request.top_k]
    write_json(directory / "candidates.json", rows)
    converter = Transformer.from_crs(ANALYSIS_CRS, "EPSG:4326", always_xy=True)
    features = []

    def add(geometry, role, properties=None):
        features.append(
            {
                "type": "Feature",
                "properties": {"role": role, **(properties or {})},
                "geometry": mapping(transform(geometry, converter.transform, interleaved=False)),
            }
        )

    for name, layer in layers.items():
        for g in layer.aligned().geometries:
            add(g, name)
    add(feasible, "feasible_area")
    add(excluded, "excluded_area")
    for r in rows:
        add(
            Point(r["x"], r["y"]),
            "candidate",
            {
                "candidate_id": r["candidate_id"],
                "rank": r["rank"],
                "score": r["score"],
                "top_k": r["rank"] <= request.top_k,
            },
        )
    write_json(directory / "map.geojson", {"type": "FeatureCollection", "features": features})
    with (directory / "ranking.csv").open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "rank",
                "candidate_id",
                "x",
                "y",
                "score",
                "hospital_m",
                "industrial_risk_m",
                "major_road_m",
            ],
        )
        writer.writeheader()
        for r in rows:
            writer.writerow(
                {k: r[k] for k in ("rank", "candidate_id", "x", "y", "score")}
                | {f"{k}_m": v for k, v in r["distances_m"].items()}
            )
    region = layers["demo_region"].aligned().geometries[0]
    minx, miny, maxx, maxy = region.bounds
    shapes = []
    colors = {
        "demo_region": "#e2e8f0",
        "feasible_area": "#86efac",
        "excluded_area": "#fca5a5",
        "hospital": "#2563eb",
        "industrial_risk": "#dc2626",
        "major_road": "#475569",
    }
    geometries = [(name, g) for name, layer in layers.items() for g in layer.aligned().geometries]
    geometries += [("feasible_area", feasible), ("excluded_area", excluded)]
    # All SVG is generated by Shapely from numeric geometry; attributes use fixed colors.
    for name, g in geometries:
        if not g.is_empty:
            shapes.append(
                g.svg(scale_factor=12, fill_color=colors[name])
                if g.geom_type != "LineString"
                else g.svg(scale_factor=12, stroke_color=colors[name])
            )
    for r in rows:
        color = "#7c3aed" if r["rank"] <= request.top_k else "#64748b"
        shapes.append(
            f'<circle cx="{r["x"]}" cy="{r["y"]}" r="{35 if r["rank"] <= request.top_k else 12}" '
            f'fill="{color}"><title>{html.escape(r["candidate_id"])} rank {r["rank"]}</title></circle>'
        )
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{minx - 100} {-maxy - 100} '
        f'{maxx - minx + 200} {maxy - miny + 200}" width="700" role="img" aria-label="合成选址地图">'
        '<g transform="scale(1,-1)">' + "".join(shapes) + "</g></svg>"
    )
    legend = " | ".join(f'<span style="color:{c}">■ {html.escape(n)}</span>' for n, c in colors.items())
    explanations = [
        f"{r['rank']}. {r['candidate_id']} 得分 {r['score']:.6f}；"
        + "；".join(f"{k} 距离 {v:.2f} m" for k, v in r["distances_m"].items())
        for r in top
    ]
    report = (
        "# 合成数据选址结果\n\n辅助决策原型，不代替法定规划、地籍核验和现场勘查。\n\n"
        "候选为250米网格中心；可能漏掉窄小可行区。地图缓冲边界为近似，筛选使用精确点到几何距离。\n\n"
        "评分：每项 1/(1+距离米/1000)，权重除以权重总和；无偏好按候选ID排序。\n\n"
        + ("\n\n".join(explanations) if top else "EMPTY_RESULT：网格中没有满足约束的候选。")
        + "\n\n元数据：\n```json\n"
        + json.dumps(metadata, ensure_ascii=False, indent=2)
        + "\n```\n"
    )
    (directory / "report.md").write_text(report, encoding="utf-8")
    (directory / "map.html").write_text(
        '<!doctype html><html lang="zh-CN"><meta charset="utf-8">'
        "<title>GeoSite 合成地图</title><h1>合成数据 · GeoSite</h1>"
        + svg
        + "<p>"
        + legend
        + "</p><pre>"
        + html.escape(report)
        + "</pre></html>",
        encoding="utf-8",
    )
    return ["candidates.json", "map.geojson", "ranking.csv", "map.html", "report.md"]
